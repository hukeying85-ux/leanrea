"""Synthetic demo data - a *plumbing* test, not a dataset.

Writes five small FASTA files plus a source manifest that the real ingestion path
reads. Sequences are generated with the composition biases typical of AMPs
(cationic + hydrophobic), so the classifier can learn something and the training
code paths are genuinely exercised. Nothing here is biology: never quote the
numbers produced on demo data.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from .config import DemoConfig

NEUTRAL = "STNQPGAD"
CATIONIC = "KRKRH"
HYDROPHOBIC = "AILMFWVY"


def _sample_peptide(rng: np.random.Generator, length: int, cationic: float, hydrophobic: float) -> str:
    residues = []
    for _ in range(length):
        u = rng.random()
        if u < cationic:
            residues.append(rng.choice(list(CATIONIC)))
        elif u < cationic + hydrophobic:
            residues.append(rng.choice(list(HYDROPHOBIC)))
        else:
            residues.append(rng.choice(list(NEUTRAL)))
    return "".join(residues)


def _unique(rng, n, length_range, cationic, hydrophobic, seen: set[str]) -> list[str]:
    out: list[str] = []
    while len(out) < n:
        length = int(rng.integers(*length_range))
        seq = _sample_peptide(rng, length, cationic, hydrophobic)
        if seq not in seen:
            seen.add(seq)
            out.append(seq)
    return out


def write_demo_sources(root: Path, cfg: DemoConfig | None = None) -> Path:
    """Create ``<root>/raw_demo/*.fasta`` and ``<root>/raw_demo/sources_demo.yaml``."""

    cfg = cfg or DemoConfig()
    rng = np.random.default_rng(cfg.seed)
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    seen: set[str] = set()

    positives = _unique(rng, cfg.n_positive, (12, 36), 0.30, 0.35, seen)
    bacterial = _unique(rng, cfg.n_bacterial, (10, 30), 0.34, 0.30, seen)
    negatives = _unique(rng, cfg.n_negative, (15, 50), 0.12, 0.22, seen)
    hard = _unique(rng, cfg.n_hard_negative, (12, 36), 0.30, 0.33, seen)
    external = _unique(rng, cfg.n_external, (12, 36), 0.28, 0.32, seen)

    def dump(name: str, seqs: list[str]) -> None:
        with open(root / f"{name}.fasta", "w", encoding="utf-8") as fh:
            for i, seq in enumerate(seqs):
                fh.write(f">{name}_{i} synthetic={name}\n{seq}\n")

    dump("demo_general_amp", positives)
    dump("demo_bacterial_amp", bacterial)
    dump("demo_negative_background", negatives)
    dump("demo_hard_negative", hard)
    dump("demo_external", external)

    manifest = root / "sources_demo.yaml"
    intros = []
    for name, layer in (
        ("demo_general_amp", "general_amp"),
        ("demo_bacterial_amp", "bacterial_amp"),
        ("demo_negative_background", "negative_background"),
        ("demo_hard_negative", "hard_negative"),
        ("demo_external", "external"),
    ):
        intros.append(
            f"  - id: {name}\n"
            f"    path: {name}.fasta\n"
            f"    format: fasta\n"
            f"    layer: {layer}\n"
            f"    label: {1 if layer in ('general_amp', 'bacterial_amp') else 0}\n"
            f"    min_len: 5\n"
            f"    max_len: 50\n"
        )
    manifest.write_text(
        "# Synthetic demo sources - generated by `python -m dualamp_lite demo`.\n"
        "# Replace with the real APD6 / DRAMP / DBAASP / CAMPR4 / UniProt exports and\n"
        "# declare the sequence + label columns of each file (see configs/sources_example.yaml).\n"
        "sources:\n" + "".join(intros),
        encoding="utf-8",
    )
    return manifest


def demo_dataframe(cfg: DemoConfig | None = None):
    """In-memory variant used by the unit tests (same distributions)."""

    import pandas as pd

    cfg = cfg or DemoConfig()
    rng = np.random.default_rng(cfg.seed)
    seen: set[str] = set()
    frames = []
    for layer, n, lr, cat, hyd, label in (
        ("general_amp", cfg.n_positive, (12, 36), 0.30, 0.35, 1),
        ("bacterial_amp", cfg.n_bacterial, (10, 30), 0.34, 0.30, 1),
        ("negative_background", cfg.n_negative, (15, 50), 0.12, 0.22, 0),
        ("hard_negative", cfg.n_hard_negative, (12, 36), 0.30, 0.33, 0),
        ("external", cfg.n_external, (12, 36), 0.28, 0.32, 0),
    ):
        for seq in _unique(rng, n, lr, cat, hyd, seen):
            frames.append({"seq": seq, "label": label, "layer": layer, "source": f"demo_{layer}"})
    df = pd.DataFrame(frames)
    for meta in ("organism", "activity", "mic", "mic_unit", "strain", "assay", "uniprot_id", "notes"):
        df[meta] = ""
    return df
